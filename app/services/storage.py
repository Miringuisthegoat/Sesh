"""Private object storage behind one small interface.

Backends: LocalStorage (development/tests) and R2Storage (Cloudflare R2 or any S3-compatible service via boto3).
Nothing here ever produces a public or permanent URL: files are served only through authorised Flask routes.
Keys are generated by `new_key()`; user-provided names never become keys.
"""
from __future__ import annotations

import os
import re
import secrets
import shutil
import tempfile
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Iterator

from flask import current_app

CHUNK = 1024 * 256
KEY_RE = re.compile(r"^(uploads|converted)/[0-9a-f]{32}\.[a-z0-9]{2,5}$")


class StorageError(Exception):
    """Storage is unavailable or an object is missing/corrupt. Usually transient."""


def new_key(prefix: str, ext: str) -> str:
    key = f"{prefix}/{secrets.token_hex(16)}.{ext.lower().lstrip('.')}"
    if not KEY_RE.match(key):
        raise ValueError("invalid key parts")
    return key


def _check_key(key: str) -> str:
    if not KEY_RE.match(key or ""):
        raise StorageError("Invalid storage key.")
    return key


class Storage(ABC):
    @abstractmethod
    def put_file(self, key: str, path: Path, content_type: str) -> None: ...

    @abstractmethod
    def open_stream(self, key: str) -> tuple[int, Iterator[bytes]]:
        """Return (size, chunk iterator). Raises StorageError if missing."""

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    def download_to(self, key: str, dest: Path) -> None:
        _, chunks = self.open_stream(key)
        with open(dest, "wb") as f:
            for c in chunks:
                f.write(c)

    def read_bytes(self, key: str, max_bytes: int = 200 * 1024 * 1024) -> bytes:
        size, chunks = self.open_stream(key)
        if size > max_bytes:
            raise StorageError("Object is too large to load.")
        return b"".join(chunks)


class LocalStorage(Storage):
    def __init__(self, root: Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        p = (self.root / _check_key(key)).resolve()
        if self.root not in p.parents:  # belt and braces on top of KEY_RE
            raise StorageError("Invalid storage key.")
        return p

    def put_file(self, key: str, path: Path, content_type: str) -> None:
        dest = self._path(key)
        dest.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=dest.parent, prefix=".part-")
        try:
            with os.fdopen(fd, "wb") as out, open(path, "rb") as src:
                shutil.copyfileobj(src, out, CHUNK)
            os.replace(tmp, dest)  # atomic: readers never see a half-written object
        except OSError as e:
            Path(tmp).unlink(missing_ok=True)
            raise StorageError("Could not write to storage.") from e

    def open_stream(self, key: str):
        p = self._path(key)
        try:
            size = p.stat().st_size
        except OSError as e:
            raise StorageError("Stored file not found.") from e

        def gen():
            with open(p, "rb") as f:
                while chunk := f.read(CHUNK):
                    yield chunk
        return size, gen()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


class R2Storage(Storage):
    """S3-compatible storage (Cloudflare R2). The bucket must stay private: no public access, no custom public domain."""

    def __init__(self, endpoint_url: str, bucket: str, access_key_id: str, secret_access_key: str):
        import boto3
        from botocore.config import Config
        if not (endpoint_url and bucket and access_key_id and secret_access_key):
            raise RuntimeError("R2 storage needs R2_ENDPOINT_URL, R2_BUCKET, R2_ACCESS_KEY_ID and R2_SECRET_ACCESS_KEY.")
        self.bucket = bucket
        self.client = boto3.client(
            "s3", endpoint_url=endpoint_url, aws_access_key_id=access_key_id, aws_secret_access_key=secret_access_key,
            region_name="auto", config=Config(signature_version="s3v4", retries={"max_attempts": 3, "mode": "standard"},
                                              connect_timeout=5, read_timeout=30))

    def put_file(self, key: str, path: Path, content_type: str) -> None:
        from botocore.exceptions import BotoCoreError, ClientError
        try:
            self.client.upload_file(str(path), self.bucket, _check_key(key), ExtraArgs={"ContentType": content_type})
        except (BotoCoreError, ClientError) as e:
            raise StorageError("Could not write to storage.") from e

    def open_stream(self, key: str):
        from botocore.exceptions import BotoCoreError, ClientError
        try:
            obj = self.client.get_object(Bucket=self.bucket, Key=_check_key(key))
        except (BotoCoreError, ClientError) as e:
            raise StorageError("Stored file not found or storage unavailable.") from e
        body = obj["Body"]

        def gen():
            try:
                yield from body.iter_chunks(CHUNK)
            finally:
                body.close()
        return int(obj["ContentLength"]), gen()

    def delete(self, key: str) -> None:
        from botocore.exceptions import BotoCoreError, ClientError
        try:
            self.client.delete_object(Bucket=self.bucket, Key=_check_key(key))
        except (BotoCoreError, ClientError) as e:
            raise StorageError("Could not delete from storage.") from e

    def exists(self, key: str) -> bool:
        from botocore.exceptions import BotoCoreError, ClientError
        try:
            self.client.head_object(Bucket=self.bucket, Key=_check_key(key))
            return True
        except ClientError as e:
            if e.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
                return False
            raise StorageError("Storage unavailable.") from e
        except BotoCoreError as e:
            raise StorageError("Storage unavailable.") from e


def get_storage() -> Storage:
    """One storage instance per app (created lazily, so config overrides in tests apply)."""
    app = current_app._get_current_object()
    st = app.extensions.get("sesh_storage")
    if st is None:
        cfg = app.config
        if cfg["STORAGE_BACKEND"] == "r2":
            st = R2Storage(cfg["R2_ENDPOINT_URL"], cfg["R2_BUCKET"], cfg["R2_ACCESS_KEY_ID"], cfg["R2_SECRET_ACCESS_KEY"])
        elif cfg["STORAGE_BACKEND"] == "local":
            root = Path(cfg["STORAGE_LOCAL_PATH"])
            if not root.is_absolute():
                root = Path(app.root_path).parent / root
            st = LocalStorage(root)
        else:
            raise RuntimeError("STORAGE_BACKEND must be 'local' or 'r2'.")
        app.extensions["sesh_storage"] = st
    return st
